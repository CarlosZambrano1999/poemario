const ts = require('typescript');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const cache = {};
function moduleFor(name) {
  if(cache[name]) return cache[name].exports;
  const file=path.join(root,name);
  const source=fs.readFileSync(file,'utf8');
  const js=ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  const m={exports:{}}; cache[name]=m;
  const req=(id)=>id==='@/data/poemas'?moduleFor('data/poemas.ts'):require(id);
  new Function('require','module','exports',js)(req,m,m.exports);
  return m.exports;
}
const data=moduleFor('data/poemas.ts');
const {generarPaginas}=moduleFor('lib/paginacion.ts');
const check=(expr,description)=>{if(!expr)throw Error(description);console.log('OK:',description)};
const medidor=(c,p,estrofas,cont)=>estrofas.flatMap(x=>x.split('\n')).length<= (cont?8:6) && estrofas.every(x=>x.split('\n').every(l=>l.length<=100));
const inicial=generarPaginas((c,p,estrofas,cont)=>estrofas.flatMap(s=>s.split("\n")).length<=24);
check(inicial.length>=16,'Genera las secciones y paginas');
check(inicial.filter(p=>p.tipo==='poema').length===9,'Los 9 poemas cortos conservan una pagina cada uno');
check(inicial.length===16, 'Mantiene 16 paginas con poemas de demostracion');
const versos=Array.from({length:121},(_,i)=>`Verso ${i+1}: esta es una linea que conservar.`);
const poemaPrueba=data.categorias[0].poemas[0];
poemaPrueba.estrofas=[versos.join('\n')];
const largo=generarPaginas(medidor);
const fragmentos=largo.filter(p=>p.tipo==='poema' && p.poema.id===poemaPrueba.id);
check(fragmentos.length>=15,'Un poema de 121 versos se reparte en muchas hojas');
check(fragmentos.every((p,i)=>p.continuacion===(i>0)),'Marca la continuacion en las hojas adicionales');
check(fragmentos.every(p=>p.estrofas.flatMap(s=>s.split('\n')).length <= (p.continuacion?8:6)),'Los versos de cada hoja caben en el limite simulado');
check(JSON.stringify(fragmentos.flatMap(p=>p.estrofas.flatMap(e=>e.split('\n'))))===JSON.stringify(versos),'Preserva orden y texto de los 121 versos');
check(largo.some(p=>p.tipo==='capitulo'&&p.categoria.id==='esperanza'),'Conserva los capitulos posteriores al poema largo');
check(largo.length>inicial.length, 'Actualiza automaticamente el total de paginas');
check(data.buscarPaginaPoema('lluvia',largo) > data.buscarPaginaPoema('lluvia',inicial), 'El indice ajusta las paginas siguientes');
poemaPrueba.estrofas=['Esto es un verso muy largo '.repeat(55)];
const medidorLargo=(c,p,estrofas,cont)=> estrofas.every(e=>e.length<=100);
const muyLargo=generarPaginas(medidorLargo).filter(p=>p.tipo==='poema'&&p.poema.id===poemaPrueba.id);
check(muyLargo.length>3,'Divide versos de longitud excepcional');
check(muyLargo.every(p=>p.estrofas.join('').length<=100),'No deja fragmentos por encima de limite');
